Route::get('/jobs/{id}', function ($id) {
    /*
        N/B:- Duplicating the $jobs array here is not ideal. It was only for
        showing an example. Ideally, I would be fetching data from a database
        or somewhere that's consistent so as to avoid having duplicate data
    */
    $jobs = [
        [
            'id' => 1,
            'title' => 'Director',
            'salary' => '$50,000'
        ],
        [
            'id' => 2,
            'title' => 'Programmer',
            'salary' => '$10,000'
        ],
        [
            'id' => 3,
            'title' => 'Teacher',
            'salary' => '$40,000'
        ]
    ];

    // Get the job id that matches the `id` passed in the url.
    $job = Arr::first($jobs, fn($job) => $job['id'] == $id);
    return view('job', ['job' => $job]);
});

